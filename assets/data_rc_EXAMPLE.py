def rc_pages(members, page_func=None, maxn=6):
    """合并成员条目的投标页码，去重保序。
    page_func：可选的页码查询函数（如 page_map.bid_spot / page_map.bid）；
    未提供时返回空串，由调用方在真实项目中回填。
    """
    if page_func is None:
        return ''
    seen, out = set(), []
    for m in members:
        s = page_func(m) or ''
        for tok in s.replace('等', ' ').replace('处', ' ').split('、'):
            tok = tok.strip()
            if tok.startswith('P'):
                n = tok[1:].strip()
                if n.isdigit() and n not in seen:
                    seen.add(n)
                    out.append('P' + n)
    if not out:
        return ''
    if len(out) > maxn:
        return '、'.join(out[:maxn]) + ' 等%d处' % len(out)
    return '、'.join(out)


def build_rc(page_func=None):
    """返回 [(编号, 问题, 等级, 原条目, 页码, 招标依据, 处理建议)]"""
    return [(no, item, lv, src, rc_pages(members, page_func), ten, act)
            for no, item, lv, src, members, ten, act in RC]


